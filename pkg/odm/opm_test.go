func TestDecodeOPMWithManeuvers(t *testing.T) {
	m, err := odm.DecodeOPM([]byte(figureG2))
	if err != nil {
		t.Fatalf("DecodeOPM: %v", err)
	}

	// These comments come between the version keyword and CREATION_DATE, which
	// is the only place a header comment may sit.
	if len(m.Header.Comments) != 2 {
		t.Errorf("header comments = %q, want 2", m.Header.Comments)
	}

	// Units are documentation, not data: the value is the same with or
	// without '[km]' after it (clause 7.7.1.1).
	sv := m.Data.StateVector
	if sv.X != 6655.9942 || sv.Y != -40218.5751 || sv.Z != -82.9177 {
		t.Errorf("position = %v %v %v", sv.X, sv.Y, sv.Z)
	}
	if sv.XDot != 3.11548208 || sv.YDot != 0.47042605 || sv.ZDot != -0.00101495 {
		t.Errorf("velocity = %v %v %v", sv.XDot, sv.YDot, sv.ZDot)
	}

	k := m.Data.Keplerian
	if k == nil {
		t.Fatal("no Keplerian elements")
	}
	if k.SemiMajorAxis != 41399.5123 || k.Eccentricity != 0.020842611 || k.GM != 398600.4415 {
		t.Errorf("Keplerian elements = %+v", k)
	}
	if k.AnomalyIsMean {
		t.Error("the anomaly was read as a mean anomaly; the message gives TRUE_ANOMALY")
	}
	if k.Anomaly != 41.922339 {
		t.Errorf("Anomaly = %v, want 41.922339", k.Anomaly)
	}

	if len(m.Data.Maneuvers) != 2 {
		t.Fatalf("read %d maneuvers, want 2", len(m.Data.Maneuvers))
	}

	first := m.Data.Maneuvers[0]
	wantIgnition := time.Date(2021, 6, 3, 9, 0, 34, 100000000, time.UTC)
	if !first.EpochIgnition.Equal(wantIgnition) {
		t.Errorf("first ignition = %v, want %v", first.EpochIgnition, wantIgnition)
	}
	if first.Duration != 132.60 || first.DeltaMass != -18.418 || first.RefFrame != "EME2000" {
		t.Errorf("first maneuver = %+v", first)
	}
	if first.DV != [3]float64{-0.023257, 0.0168316, -0.00893444} {
		t.Errorf("first DV = %v", first.DV)
	}
	// Three, not two. The document writes "COMMENT 2 planned maneuvers" ahead
	// of the first maneuver's own two comment lines, meaning it for the whole
	// group. Nothing in the format says so: clause 7.8.7 attaches a comment to
	// the logical block that follows it, and each maneuver is its own block,
	// so all three land on the first one. A reader cannot recover the author's
	// intent here, and neither can this package.
	if len(first.Comments) != 3 {
		t.Errorf("first maneuver comments = %q, want 3", first.Comments)
	}

	// Clause 3.2.4.7: a zero duration marks an impulsive manoeuvre.
	second := m.Data.Maneuvers[1]
	if second.Duration != 0 {
		t.Errorf("second duration = %v, want 0 for an impulsive maneuver", second.Duration)
	}
	if second.RefFrame != "RTN" {
		t.Errorf("second frame = %q, want RTN", second.RefFrame)
	}
}

// Encoding and decoding must agree on the values. The octets will not match
// the document's, because clause 7.5.6 makes trailing zeroes optional and
// clauses 7.4.5 to 7.4.7 make the alignment insignificant, so the same message
// has many spellings.
func TestOPMRoundTrip(t *testing.T) {
	for name, input := range map[string]string{"figure G-1": figureG1, "figure G-2": figureG2} {
		t.Run(name, func(t *testing.T) {
			first, err := odm.DecodeOPM([]byte(input))
			if err != nil {
				t.Fatalf("DecodeOPM: %v", err)
			}
			encoded, err := first.Encode()
			if err != nil {
				t.Fatalf("Encode: %v", err)
			}
			second, err := odm.DecodeOPM(encoded)
			if err != nil {
				t.Fatalf("DecodeOPM on our own output: %v\n%s", err, encoded)
			}

			if !second.Data.StateVector.Epoch.Equal(first.Data.StateVector.Epoch) {
				t.Errorf("epoch changed: %v then %v",
					first.Data.StateVector.Epoch, second.Data.StateVector.Epoch)
			}
			compare(t, "X", first.Data.StateVector.X, second.Data.StateVector.X)
			compare(t, "Z_DOT", first.Data.StateVector.ZDot, second.Data.StateVector.ZDot)

			if len(second.Data.Maneuvers) != len(first.Data.Maneuvers) {
				t.Fatalf("maneuver count changed: %d then %d",
					len(first.Data.Maneuvers), len(second.Data.Maneuvers))
			}
			for i := range first.Data.Maneuvers {
				compare(t, "delta mass", first.Data.Maneuvers[i].DeltaMass, second.Data.Maneuvers[i].DeltaMass)
				compare(t, "DV 1", first.Data.Maneuvers[i].DV[0], second.Data.Maneuvers[i].DV[0])
			}
		})
	}
}

func compare(t *testing.T, name string, want, got float64) {
	t.Helper()
	if math.Abs(got-want) > 1e-12*math.Max(1, math.Abs(want)) {
		t.Errorf("%s changed: %v then %v", name, want, got)
	}
}

func TestDecodeOPMRejects(t *testing.T) {
	tests := []struct {
		name  string
		input string
		want  error
	}{
		{
			name:  "a keyword no table lists",
			input: figureG1 + "NOT_A_KEYWORD = 1\n",
			want:  odm.ErrUnknownKeyword,
		},
		{
			name:  "a repeated keyword",
			input: figureG1 + "DRAG_COEFF = 2.5\n",
			want:  odm.ErrDuplicateKeyword,
		},
		{
			name:  "both anomalies",
			input: figureG2 + "MEAN_ANOMALY = 41.0\n",
			want:  odm.ErrBothAnomalies,
		},
		{
			name:  "a maneuver parameter before its ignition epoch",
			input: figureG1 + "MAN_DURATION = 10.0\n",
			want:  odm.ErrKeywordOutOfOrder,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if _, err := odm.DecodeOPM([]byte(tt.input)); !errors.Is(err, tt.want) {
				t.Errorf("DecodeOPM = %v, want %v", err, tt.want)
			}
		})
	}
}

// Clause 3.2.4.9 makes mass mandatory once a manoeuvre is present, and
// clause 3.2.4.7 requires the mass change to be negative.
func TestOPMManeuverRules(t *testing.T) {
	base, err := odm.DecodeOPM([]byte(figureG2))
	if err != nil {
		t.Fatalf("DecodeOPM: %v", err)
	}

	t.Run("a maneuver without mass", func(t *testing.T) {
		m := *base
		data := m.Data
		data.Spacecraft = nil
		m.Data = data
		if err := m.Validate(); !errors.Is(err, odm.ErrManeuverWithoutMass) {
			t.Errorf("Validate = %v, want ErrManeuverWithoutMass", err)
		}
	})

	t.Run("a maneuver that gains mass", func(t *testing.T) {
		m := *base
		maneuvers := append([]odm.Maneuver(nil), m.Data.Maneuvers...)
		maneuvers[0].DeltaMass = 1.0
		data := m.Data
		data.Maneuvers = maneuvers
		m.Data = data
		if err := m.Validate(); !errors.Is(err, odm.ErrDeltaMassNotNegative) {
			t.Errorf("Validate = %v, want ErrDeltaMassNotNegative", err)
		}
	})
}
