// Figure G-1 of CCSDS 502.0-B-3, transcribed. The alignment is the document's,
// because clauses 7.4.5 to 7.4.7 make it insignificant and a reader has to
// prove that rather than assume it.
const figureG1 = `CCSDS_OPM_VERS = 3.0
CREATION_DATE = 2022-11-06T09:23:57
ORIGINATOR     = JAXA

COMMENT          GEOCENTRIC, CARTESIAN, EARTH FIXED
OBJECT_NAME    = OSPREY 5
OBJECT_ID      = 1998-999A
CENTER_NAME    = EARTH
REF_FRAME      = ITRF2000
TIME_SYSTEM    = UTC

EPOCH =           2022-12-18T14:28:15.1172
X =               6503.514000
Y =               1239.647000
Z =               -717.490000
X_DOT =             -0.873160
Y_DOT =              8.740420
Z_DOT =             -4.191076
MASS =            3000.000000
SOLAR_RAD_AREA =    18.770000
SOLAR_RAD_COEFF =    1.000000
DRAG_AREA =         18.770000
DRAG_COEFF =         2.500000
`

func TestDecodeSimpleOPM(t *testing.T) {
	m, err := odm.DecodeOPM([]byte(figureG1))
	if err != nil {
		t.Fatalf("DecodeOPM: %v", err)
	}

	if m.Header.Version != "3.0" {
		t.Errorf("Version = %q, want 3.0", m.Header.Version)
	}
	if m.Header.Originator != "JAXA" {
		t.Errorf("Originator = %q, want JAXA", m.Header.Originator)
	}
	wantCreated := time.Date(2022, 11, 6, 9, 23, 57, 0, time.UTC)
	if !m.Header.CreationDate.Equal(wantCreated) {
		t.Errorf("CreationDate = %v, want %v", m.Header.CreationDate, wantCreated)
	}

	// The COMMENT sits after ORIGINATOR, so it opens the metadata section
	// rather than the header (clause 7.8.7).
	if len(m.Header.Comments) != 0 {
		t.Errorf("header comments = %q, want none", m.Header.Comments)
	}
	if len(m.Metadata.Comments) != 1 ||
		m.Metadata.Comments[0] != "         GEOCENTRIC, CARTESIAN, EARTH FIXED" {
		t.Errorf("metadata comments = %q", m.Metadata.Comments)
	}

	md := m.Metadata
	if md.ObjectName != "OSPREY 5" || md.ObjectID != "1998-999A" ||
		md.CenterName != "EARTH" || md.RefFrame != "ITRF2000" || md.TimeSystem != "UTC" {
		t.Errorf("metadata = %+v", md)
	}

	sv := m.Data.StateVector
	wantEpoch := time.Date(2022, 12, 18, 14, 28, 15, 117200000, time.UTC)
	if !sv.Epoch.Equal(wantEpoch) {
		t.Errorf("Epoch = %v, want %v", sv.Epoch, wantEpoch)
	}
	for _, tt := range []struct {
		name string
		got  float64
		want float64
	}{
		{"X", sv.X, 6503.514},
		{"Y", sv.Y, 1239.647},
		{"Z", sv.Z, -717.49},
		{"X_DOT", sv.XDot, -0.87316},
		{"Y_DOT", sv.YDot, 8.74042},
		{"Z_DOT", sv.ZDot, -4.191076},
	} {
		if tt.got != tt.want {
			t.Errorf("%s = %v, want %v", tt.name, tt.got, tt.want)
		}
	}

	if m.Data.Keplerian != nil {
		t.Error("a Keplerian block was read from a message that has none")
	}
	s := m.Data.Spacecraft
	if s == nil {
		t.Fatal("no spacecraft parameters")
	}
	if !s.HasMass() || s.Mass != 3000 {
		t.Errorf("Mass = %v (given %v), want 3000", s.Mass, s.HasMass())
	}
	if s.SolarRadArea != 18.77 || s.SolarRadCoeff != 1 || s.DragArea != 18.77 || s.DragCoeff != 2.5 {
		t.Errorf("spacecraft parameters = %+v", s)
	}
}

